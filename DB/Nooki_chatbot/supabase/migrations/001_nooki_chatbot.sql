-- Nooki 홈페이지 챗봇 (RAG + Gemini)
-- 실습용 documents/chunks 와 분리된 전용 테이블. 의존: extensions.vector, public.split_into_chunks

-- 1) 지식 베이스
create table public.nooki_documents (
  id bigint generated by default as identity primary key,
  title text not null,
  source text,
  created_at timestamptz not null default now()
);

create table public.nooki_chunks (
  id bigint generated by default as identity primary key,
  document_id bigint not null references public.nooki_documents(id) on update cascade on delete cascade,
  chunk_index int not null default 0,
  content text not null,
  embedding extensions.vector(768),
  created_at timestamptz not null default now()
);

create index nooki_chunks_document_id_idx on public.nooki_chunks (document_id);
create index nooki_chunks_embedding_hnsw_idx on public.nooki_chunks using hnsw (embedding extensions.vector_cosine_ops);

-- 2) 요청 기록 (IP 해시 기준 사용량 제한용, 질문 내용은 저장하지 않음)
create table public.nooki_chat_requests (
  id bigint generated by default as identity primary key,
  ip_hash text not null,
  created_at timestamptz not null default now()
);

create index nooki_chat_requests_ip_time_idx on public.nooki_chat_requests (ip_hash, created_at);

-- 3) RLS: 정책 없음 = anon/authenticated 직접 접근 차단. Edge Function(service_role)만 읽고 씀
alter table public.nooki_documents enable row level security;
alter table public.nooki_chunks enable row level security;
alter table public.nooki_chat_requests enable row level security;

-- 4) 유사 청크 검색
create function public.nooki_match_chunks(
  query_embedding extensions.vector(768),
  match_count int default 5,
  match_threshold float default 0
)
returns table (id bigint, document_id bigint, title text, chunk_index int, content text, similarity float)
language sql stable
security invoker
set search_path = ''
as $$
  select c.id, c.document_id, d.title, c.chunk_index, c.content,
         1 - (c.embedding operator(extensions.<=>) query_embedding) as similarity
  from public.nooki_chunks c
  join public.nooki_documents d on d.id = c.document_id
  where c.embedding is not null
    and 1 - (c.embedding operator(extensions.<=>) query_embedding) > match_threshold
  order by c.embedding operator(extensions.<=>) query_embedding
  limit match_count;
$$;

revoke execute on function public.nooki_match_chunks(extensions.vector, int, float) from public, anon, authenticated;
